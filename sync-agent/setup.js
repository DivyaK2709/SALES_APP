// setup.js
//
// Run this ONCE on each client/store PC (double-click setup.bat, or
// `node setup.js`). Asks a few questions about that store's local SQL
// Server and writes .env for you — no manual file editing needed.

const readline = require('readline');
const fs = require('fs');
const path = require('path');
const sql = require('mssql');

const rl = readline.createInterface({ input: process.stdin, output: process.stdout });
const ask = (q, def) =>
  new Promise((resolve) => {
    rl.question(def ? `${q} [${def}]: ` : `${q}: `, (answer) => {
      resolve(answer.trim() || def || '');
    });
  });

async function main() {
  console.log('\n=== FreshMart Sync Agent — First-time setup ===\n');
  console.log("This collects THIS store's local SQL Server details and a unique");
  console.log('store code, then saves them to .env. Run this once per store PC.\n');

  const storeUniqueCode = (await ask('Unique code for this store (e.g. YNOT01)')).toUpperCase();
  const storeCcode = await ask('Numeric CCode for this store (matches AcCompany.CCode)', '1');

  console.log('\n-- Local SQL Server --');
  const server = await ask('Server (usually "localhost" if this SQL Server is on this PC)', 'localhost');
  const useInstance = (await ask('Named instance? (e.g. SQLEXPRESS) — leave blank if none', 'SQLEXPRESS'));
  const port = useInstance ? '' : await ask('Port', '1433');
  const database = await ask('Database name', 'ynot');
  const user = await ask('SQL login username', 'sync_reader');
  const password = await ask('SQL login password');

  console.log('\n-- Cloud API --');
  const cloudUrl = await ask('Cloud API URL', 'http://localhost:3000');
  const syncKey = await ask('Sync secret key (must match freshmart-backend/.env SYNC_SECRET_KEY)');

  // Test the local connection before saving anything
  console.log('\nTesting local database connection...');
  const testConfig = {
    server,
    database,
    user,
    password,
    options: {
      encrypt: false,
      trustServerCertificate: true,
      ...(useInstance ? { instanceName: useInstance } : {}),
    },
    ...(port ? { port: parseInt(port, 10) } : {}),
  };

  try {
    const pool = await sql.connect(testConfig);
    await pool.close();
    console.log('✅ Connected successfully.\n');
  } catch (err) {
    console.log(`❌ Could not connect: ${err.message}`);
    console.log('Saving your answers to .env anyway — fix the connection details there and re-run "node sync.js" once ready.\n');
  }

  const envContent = `# Generated by setup.js on ${new Date().toISOString()}

STORE_UNIQUE_CODE=${storeUniqueCode}
STORE_CODE=${storeCcode}

LOCAL_DB_SERVER=${server}
${useInstance ? `LOCAL_DB_INSTANCE=${useInstance}` : `# LOCAL_DB_INSTANCE=`}
${port ? `LOCAL_DB_PORT=${port}` : `# LOCAL_DB_PORT=`}
LOCAL_DB_DATABASE=${database}
LOCAL_DB_USER=${user}
LOCAL_DB_PASSWORD=${password}
LOCAL_DB_ENCRYPT=false
LOCAL_DB_TRUST_SERVER_CERT=true

CLOUD_API_URL=${cloudUrl}
SYNC_SECRET_KEY=${syncKey}
`;

  fs.writeFileSync(path.join(__dirname, '.env'), envContent);
  console.log('Saved .env. You can now run "node sync.js" (or run-sync.bat) to sync this store.\n');

  rl.close();
}

main().catch((err) => {
  console.error('Setup failed:', err.message);
  rl.close();
  process.exit(1);
});
